// goTree writes a small tree of Go to measure.
func goTree(t *testing.T, files map[string]string) string {
	t.Helper()

	dir := t.TempDir()
	for name, body := range files {
		full := filepath.Join(dir, name)
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			t.Fatalf("making %s: %v", full, err)
		}
		if err := os.WriteFile(full, []byte(body), 0o644); err != nil {
			t.Fatalf("writing %s: %v", full, err)
		}
	}
	return dir
}

func TestReadTree(t *testing.T) {
	dir := goTree(t, map[string]string{
		"a.go":             "package a\n\n// A reads the frame.\nfunc A() {}\n",
		"deep/b.go":        "package b\n\n// B writes the frame.\nfunc B() {}\n",
		"notes.txt":        "ignored prose",
		"vendor/v/v.go":    "package v\n\n// V is somebody else's.\nfunc V() {}\n",
		"testdata/t.go":    "package t\n\n// T is a fixture.\nfunc T() {}\n",
		"broken.go":        "package a\n\nfunc A( {\n",
		"generated.go":     "// Code generated by a program. DO NOT EDIT.\n\npackage a\n\n// G is generated.\nfunc G() {}\n",
		"licence/l.go":     "// Copyright 2009 The Go Authors. All rights reserved.\n\npackage l\n",
		"licence/use.go":   "// Use of this source code is governed by a BSD-style license.\n\npackage l\n",
		"licence/own.go":   "package l\n\n// Own reads the frame.\nfunc Own() {}\n",
		"deep/deeper/c.go": "package c\n\n// C holds the frame.\nfunc C() {}\n",
	})

	corpus, err := readTree(dir)
	if err != nil {
		t.Fatalf("readTree() error = %v", err)
	}

	var text []string
	for _, block := range corpus.Blocks {
		text = append(text, block.Text)
		if block.Prose {
			t.Errorf("a baseline block is marked as markdown: %+v", block)
		}
		if block.Line == 0 {
			t.Errorf("a baseline block names no line: %+v", block)
		}
	}
	joined := strings.Join(text, " | ")

	for _, want := range []string{"A reads the frame.", "B writes the frame.", "C holds the frame.", "Own reads the frame."} {
		if !strings.Contains(joined, want) {
			t.Errorf("readTree() missed %q: %q", want, joined)
		}
	}
	for _, unwanted := range []string{"somebody else", "a fixture", "is generated", "Copyright", "Use of this source"} {
		if strings.Contains(joined, unwanted) {
			t.Errorf("readTree() read %q, which is not prose anyone here wrote: %q", unwanted, joined)
		}
	}
}

func TestReadTreeRefusesATreeWithNoComments(t *testing.T) {
	dir := goTree(t, map[string]string{"a.go": "package a\n\nfunc A() {}\n"})

	if _, err := readTree(dir); err == nil {
		t.Error("readTree() measured a tree holding no prose")
	}
	if _, err := readTree(filepath.Join(dir, "absent")); err == nil {
		t.Error("readTree() took a path that is not there")
	}
}

func TestLoadBaselineMeasuresAndKeeps(t *testing.T) {
	dir := goTree(t, map[string]string{"a.go": "package a\n\n// A reads the frame beside the pool.\nfunc A() {}\n"})

	got, err := LoadBaseline(dir, 2)
	if err != nil {
		t.Fatalf("LoadBaseline() error = %v", err)
	}

	if got.Name != dir || got.Size != 2 {
		t.Errorf("the key reads %q/%d, want %q/2", got.Name, got.Size, dir)
	}
	if got.Counts == nil || got.Counts.Words == 0 {
		t.Fatalf("the measure counted no words: %+v", got.Counts)
	}
	if got.Density.Blocks != 1 {
		t.Errorf("got %d blocks, want 1", got.Density.Blocks)
	}
}

func TestReadBaselineRoundTrip(t *testing.T) {
	file := filepath.Join(t.TempDir(), "kept.json")
	writeBaseline(file, &Baseline{
		Name:    "/some/tree",
		Size:    3,
		Counts:  &Counts{Grams: map[string]*Gram{"is what": {Skeleton: "is what", Count: 2, Line: 4}}, Words: 100},
		Density: Density{Blocks: 3, Words: 100, BlockWords: 11, Subordinators: 12.5},
	})

	got, err := readBaseline(file)
	if err != nil {
		t.Fatalf("readBaseline() error = %v", err)
	}
	if got.Name != "/some/tree" || got.Size != 3 || got.Counts.Words != 100 {
		t.Errorf("the round trip lost the key or the counts: %+v", got)
	}
	if gram := got.Counts.Grams["is what"]; gram == nil || gram.Count != 2 || gram.Line != 4 {
		t.Errorf("the gram came back as %+v", gram)
	}
	if got.Density.Subordinators != 12.5 {
		t.Errorf("the density came back as %+v", got.Density)
	}
}

func TestReadBaselineRefusesRubbish(t *testing.T) {
	dir := t.TempDir()

	for name, body := range map[string]string{
		"not json":  "{",
		"no counts": `{"name":"/t","size":2}`,
		"no words":  `{"name":"/t","size":2,"counts":{"Grams":{},"Words":0}}`,
	} {
		t.Run(name, func(t *testing.T) {
			file := filepath.Join(dir, strings.ReplaceAll(name, " ", "-")+".json")
			if err := os.WriteFile(file, []byte(body), 0o644); err != nil {
				t.Fatalf("writing %s: %v", file, err)
			}
			if _, err := readBaseline(file); err == nil {
				t.Errorf("readBaseline() took %q", body)
			}
		})
	}

	if _, err := readBaseline(filepath.Join(dir, "absent.json")); err == nil {
		t.Error("readBaseline() took a file that is not there")
	}
}

// A directory nobody can write is not a reason to refuse the measure: the run
// that wanted the baseline already holds one.
func TestWriteBaselineSurvivesAClosedDoor(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "locked")
	if err := os.MkdirAll(dir, 0o500); err != nil {
		t.Fatalf("locking the directory: %v", err)
	}

	writeBaseline(filepath.Join(dir, "sub", "kept.json"), &Baseline{Name: "/t", Counts: &Counts{}})

	// A baseline the encoder refuses leaves no file either.
	writeBaseline(filepath.Join(t.TempDir(), "kept.json"), &Baseline{
		Name:   "/t",
		Counts: &Counts{Grams: map[string]*Gram{"x": {}}, Words: 1},
	})
}

func TestBaselineEncodesAsJSON(t *testing.T) {
	body, err := json.Marshal(&Baseline{Name: "/t", Size: 2, Counts: &Counts{Grams: map[string]*Gram{}}})
	if err != nil {
		t.Fatalf("Marshal() error = %v", err)
	}
	if !strings.Contains(string(body), `"size":2`) {
		t.Errorf("the encoding lost the key: %s", body)
	}
}

